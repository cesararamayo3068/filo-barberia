CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE TABLE admin_user (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username varchar(100) NOT NULL UNIQUE,
 password_hash varchar(100) NOT NULL
);
CREATE TABLE client (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 name varchar(80) NOT NULL,
 phone varchar(32) NOT NULL DEFAULT '',
 notes varchar(500) NOT NULL DEFAULT '',
 active boolean NOT NULL DEFAULT true
);
CREATE TABLE barber (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 name varchar(80) NOT NULL,
 active boolean NOT NULL DEFAULT true
);
CREATE TABLE service (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 name varchar(80) NOT NULL,
 duration integer NOT NULL CHECK(duration BETWEEN 15 AND 240 AND duration % 5 = 0),
 price numeric(12,2) NOT NULL CHECK(price >= 0),
 active boolean NOT NULL DEFAULT true
);
CREATE TABLE appointment (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0,
 client_id bigint NOT NULL REFERENCES client,
 barber_id bigint NOT NULL REFERENCES barber,
 service_id bigint NOT NULL REFERENCES service,
 start_at timestamp NOT NULL,
 end_at timestamp NOT NULL,
 duration integer NOT NULL CHECK(duration BETWEEN 15 AND 240),
 price numeric(12,2) NOT NULL CHECK(price >= 0),
 status varchar(20) NOT NULL CHECK(status IN ('CONFIRMED','PENDING','COMPLETE','CANCELLED')),
 notes varchar(500) NOT NULL DEFAULT '',
 CHECK(end_at = start_at + duration * interval '1 minute'),
 CHECK(start_at::date = end_at::date),
 CHECK(start_at::time >= time '08:00' AND end_at::time <= time '20:00'),
 CONSTRAINT no_barber_overlap EXCLUDE USING gist
 (barber_id WITH =, tsrange(start_at,end_at,'[)') WITH &&)
 WHERE (status <> 'CANCELLED')
);
CREATE INDEX appointment_client_idx ON appointment(client_id, start_at);
CREATE INDEX appointment_start_idx ON appointment(start_at);
